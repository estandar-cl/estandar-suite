/**
 * Meta Conversions API (CAPI) exporter for Signal Core.
 *
 * Sends commercial events to Meta via server-side CAPI.
 * Designed to work alongside (or without) a client-side Meta Pixel.
 * When both are active, use signal_uuid as event_id for deduplication.
 *
 * Required wp_options:
 *   estandar_signal_core_meta_pixel_id      — Meta Pixel ID (numeric string)
 *   estandar_signal_core_meta_access_token  — System User Access Token
 *
 * Optional:
 *   estandar_signal_core_meta_test_event_code — Test event code from Meta Events Manager
 */
class Estandar_Signal_Core_Meta_Capi implements Estandar_Signal_Core_Exporter_Interface {

	const API_VERSION_DEFAULT = 'v19.0';

	/**
	 * Meta standard event names for each signal event.
	 * Events not listed here are not exported to Meta.
	 */
	const EVENT_MAP = array(
		'lead_created'   => 'Lead',
		'meeting_booked' => 'Schedule',
		'sale_closed'    => 'Purchase',
	);

	private string $pixel_id;
	private string $access_token;
	private string $test_event_code;

	public function __construct( string $pixel_id, string $access_token, string $test_event_code = '' ) {
		$this->pixel_id        = $pixel_id;
		$this->access_token    = $access_token;
		$this->test_event_code = $test_event_code;
	}

	public function get_id(): string {
		return 'meta_capi';
	}

	/**
	 * Resolve the Meta Graph API version at runtime.
	 * Default: self::API_VERSION_DEFAULT.
	 * Override via filter 'estandar_signal_core_meta_api_version' or
	 * constant 'ESTANDAR_SIGNAL_CORE_META_API_VERSION'.
	 */
	public static function api_version(): string {
		if ( defined( 'ESTANDAR_SIGNAL_CORE_META_API_VERSION' ) ) {
			return (string) ESTANDAR_SIGNAL_CORE_META_API_VERSION;
		}
		$filtered = apply_filters( 'estandar_signal_core_meta_api_version', '' );
		if ( $filtered !== '' ) {
			return $filtered;
		}
		return self::API_VERSION_DEFAULT;
	}

	public function supports_event( string $event_name ): bool {
		return isset( self::EVENT_MAP[ $event_name ] );
	}

	/**
	 * Send a signal to Meta CAPI.
	 *
	 * Phase 3: consumes ONLY the persisted technical contract row from
	 * es_signal_events. It never reads es_leads/es_lead_submissions, never
	 * inspects commercial status/sales_stage, never reconstructs event_name and
	 * applies no business logic. QA/test exclusion is decided upstream at
	 * emission time (a QA lead never produces an AdvertisingEvent, so it never
	 * reaches this row). The event_name → Meta standard event mapping is
	 * localized here (EVENT_MAP).
	 *
	 * @param  array $signal Full row from es_signal_events (ARRAY_A).
	 * @return bool          True = exported. False = transient failure (will retry).
	 * @throws \Exception    Permanent failure (bad credentials, invalid pixel, etc.)
	 */
	public function export( array $signal ): bool {
		$event_name = (string) ( $signal['event_name'] ?? '' );
		$meta_name  = self::EVENT_MAP[ $event_name ] ?? '';
		if ( $meta_name === '' ) {
			return true; // Nothing to send — treat as success.
		}

		$event_time = (string) ( $signal['event_time'] ?? '' );
		$timestamp  = $event_time !== '' ? strtotime( $event_time ) : time();
		if ( ! $timestamp ) {
			$timestamp = time();
		}

		// ── User data ─────────────────────────────────────────────────────────────
		// email_hash / phone_hash are SHA-256(normalized_value) as of schema 0.2.0,
		// generated by Repository::advertising_hash(). Meta expects SHA-256 lowercase hex.
		$user_data = array(
			'client_ip_address' => '',   // Not stored — omit.
			'client_user_agent' => '',   // Not stored — omit.
		);

		$email_hash = (string) ( $signal['email_hash'] ?? '' );
		if ( $email_hash !== '' ) {
			$user_data['em'] = array( $email_hash );
		}

		$phone_hash = (string) ( $signal['phone_hash'] ?? '' );
		if ( $phone_hash !== '' ) {
			$user_data['ph'] = array( $phone_hash );
		}

		$meta_fbc = (string) ( $signal['meta_fbc'] ?? '' );
		if ( $meta_fbc !== '' ) {
			$user_data['fbc'] = $meta_fbc;
		}

		$meta_fbp = (string) ( $signal['meta_fbp'] ?? '' );
		if ( $meta_fbp !== '' ) {
			$user_data['fbp'] = $meta_fbp;
		}

		// external_id: stable hashed identifier for this lead across events.
		$identity   = $this->decode_identity( (string) ( $signal['identity_json'] ?? '' ) );
		$lead_uuid  = (string) ( $identity['lead_uuid'] ?? '' );
		if ( $lead_uuid !== '' ) {
			$user_data['external_id'] = array( hash( 'sha256', $lead_uuid ) );
		}

		// Remove empty placeholder strings added above.
		$user_data = array_filter( $user_data, static function ( $v ) {
			return $v !== '' && $v !== array() && $v !== null;
		} );

		// ── Custom data ───────────────────────────────────────────────────────────
		$custom_data = array(
			'project_slug' => (string) ( $signal['project_slug'] ?? '' ),
		);

		// For Purchase events, include value if available.
		if ( $meta_name === 'Purchase' ) {
			$value = (float) ( $signal['value_decimal'] ?? 0 );
			$custom_data['value']    = $value > 0 ? $value : 0;
			$custom_data['currency'] = (string) ( $signal['currency'] ?? 'CLP' );
		}

		// ── Event payload ─────────────────────────────────────────────────────────
		$event = array(
			'event_name'       => $meta_name,
			'event_time'       => $timestamp,
			'action_source'    => 'website',
			'event_id'         => (string) ( $signal['signal_uuid'] ?? wp_generate_uuid4() ),
			'event_source_url' => home_url( '/' ),
			'user_data'        => $user_data,
			'custom_data'      => $custom_data,
		);

		$body = array( 'data' => array( $event ) );
		if ( $this->test_event_code !== '' ) {
			$body['test_event_code'] = $this->test_event_code;
		}

		// ── HTTP request ──────────────────────────────────────────────────────────
		$endpoint = sprintf(
			'https://graph.facebook.com/%s/%s/events?access_token=%s',
			self::api_version(),
			rawurlencode( $this->pixel_id ),
			rawurlencode( $this->access_token )
		);

		$response = wp_remote_post(
			$endpoint,
			array(
				'body'    => wp_json_encode( $body ),
				'headers' => array( 'Content-Type' => 'application/json' ),
				'timeout' => 15,
			)
		);

		// ── Response handling ─────────────────────────────────────────────────────
		if ( is_wp_error( $response ) ) {
			// Network error — transient, will retry.
			return false;
		}

		$http_code = (int) wp_remote_retrieve_response_code( $response );
		$body_raw  = wp_remote_retrieve_body( $response );
		$decoded   = json_decode( $body_raw, true );

		if ( $http_code === 200 ) {
			return true;
		}

		// 4xx: permanent failure (bad credentials, invalid pixel, malformed data).
		if ( $http_code >= 400 && $http_code < 500 ) {
			$api_message = (string) ( $decoded['error']['message'] ?? "HTTP {$http_code}" );
			throw new \Exception( "Meta CAPI permanent error: {$api_message}" );
		}

		// 5xx or unexpected: transient, will retry.
		return false;
	}

	// ── Helpers ───────────────────────────────────────────────────────────────────

	private function decode_identity( string $json ): array {
		if ( $json === '' ) {
			return array();
		}
		$decoded = json_decode( $json, true );
		return is_array( $decoded ) ? $decoded : array();
	}
}
